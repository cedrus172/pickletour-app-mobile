// Keep glyph tables unchanged; isolate conflicting native PostScript names.
// No font editor dependency is needed: only the SFNT `name` table is rebuilt.
const fs = require('node:fs');
const path = require('node:path');
const { createHash } = require('node:crypto');
const root = path.resolve(__dirname, '..');
const vendor = path.join(root, 'node_modules/@expo/vector-icons/build');
const output = path.join(root, 'assets/fonts/icons');
const sets = ['AntDesign', 'Feather', 'Ionicons', 'MaterialCommunityIcons', 'MaterialIcons', 'Octicons', 'FontAwesome', 'FontAwesome5_Regular', 'FontAwesome5_Solid', 'FontAwesome5_Brands'];

function checksum(data) {
  let sum = 0;
  for (let offset = 0; offset < data.length; offset += 4) {
    let word = 0;
    for (let i = 0; i < 4; i++) word = (word << 8) | (data[offset + i] || 0);
    sum = (sum + (word >>> 0)) >>> 0;
  }
  return sum;
}

function renameNameTable(table, name) {
  const count = table.readUInt16BE(2);
  const stringsAt = table.readUInt16BE(4);
  const records = [];
  const strings = [];
  let length = 0;
  for (let i = 0; i < count; i++) {
    const record = Buffer.from(table.subarray(6 + i * 12, 18 + i * 12));
    const platform = record.readUInt16BE(0);
    const id = record.readUInt16BE(6);
    const offset = record.readUInt16BE(10);
    let value = Buffer.from(table.subarray(stringsAt + offset, stringsAt + offset + record.readUInt16BE(8)));
    if ([1, 3, 4, 6, 16].includes(id)) {
      value = Buffer.from(name, platform === 0 || platform === 3 ? 'utf16le' : 'ascii');
      if (platform === 0 || platform === 3) value.swap16();
    }
    record.writeUInt16BE(value.length, 8);
    record.writeUInt16BE(length, 10);
    length += value.length;
    records.push(record);
    strings.push(value);
  }
  const header = Buffer.alloc(6);
  header.writeUInt16BE(count, 2);
  header.writeUInt16BE(6 + count * 12, 4);
  return Buffer.concat([header, ...records, ...strings]);
}

function isolateFont(source, name) {
  const count = source.readUInt16BE(4);
  const header = Buffer.from(source.subarray(0, 12 + count * 16));
  const chunks = [header];
  let cursor = header.length;
  let headAt = 0;
  for (let i = 0; i < count; i++) {
    const recordAt = 12 + i * 16;
    const tag = source.toString('ascii', recordAt, recordAt + 4);
    const offset = source.readUInt32BE(recordAt + 8);
    let table = Buffer.from(source.subarray(offset, offset + source.readUInt32BE(recordAt + 12)));
    if (tag === 'name') table = renameNameTable(table, name);
    if (tag === 'head') {
      table.writeUInt32BE(0, 8);
      headAt = cursor;
    }
    header.writeUInt32BE(checksum(table), recordAt + 4);
    header.writeUInt32BE(cursor, recordAt + 8);
    header.writeUInt32BE(table.length, recordAt + 12);
    const padding = Buffer.alloc((4 - table.length % 4) % 4);
    chunks.push(table, padding);
    cursor += table.length + padding.length;
  }
  const font = Buffer.concat(chunks);
  if (!headAt) throw new Error('Missing head table');
  font.writeUInt32BE((0xb1b0afba - checksum(font)) >>> 0, headAt + 8);
  if (checksum(font) !== 0xb1b0afba) throw new Error('Invalid font checksum');
  return font;
}

fs.mkdirSync(output, { recursive: true });
const entries = sets.map((set) => {
  const source = fs.readFileSync(path.join(vendor, 'vendor/react-native-vector-icons/Fonts', set + '.ttf'));
  const fa5Families = {
    FontAwesome5_Regular: ['FontAwesome5Free-Regular', 'FontAwesome5Free-Light'],
    FontAwesome5_Solid: ['FontAwesome5Free-Solid'],
    FontAwesome5_Brands: ['FontAwesome5Free-Brand'],
  };
  const families = fa5Families[set] || [fs.readFileSync(path.join(vendor, set + '.js'), 'utf8').match(/createIconSet\(glyphMap, '([^']+)'/)[1]];
  const hash = createHash('sha256').update(source).digest('hex').slice(0, 12);
  const name = `PTour${set}-${hash}`;
  fs.writeFileSync(path.join(output, set + '.ttf'), isolateFont(source, name));
  return families.map(family => `  ${JSON.stringify(family)}: { postScriptName: ${JSON.stringify(name)}, source: require('./${set}.ttf') },`).join("\n");
});
fs.writeFileSync(path.join(output, 'index.ts'), '// Generated by scripts/generate-isolated-icon-fonts.cjs. Preserve upstream glyph tables and licenses.\nexport const ISOLATED_ICON_ASSETS = {\n' + entries.join('\n') + '\n} as const;\n');
console.log(`Generated ${sets.length} isolated icon fonts; glyph tables unchanged.`);
